#list
fruits = ["apple","banana","mango"]
print(fruits)
print(fruits[0])
print(fruits[1])

# adding an item
fruits = ["apple","banana"]
fruits.append("mango")
print(fruits)


# tuple
numbers = (10,20,30,40)
print(numbers)
print(numbers[0])
print(numbers[2])

# tuple with duplicate values
colors = ("red","blue","red","green")
print(colors)

# set
numbers = {10,20,30,20,50}
print(numbers)